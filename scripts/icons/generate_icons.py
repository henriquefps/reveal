#!/usr/bin/env python3
"""Generate Phosphor ImageVectors for Reveal (no third-party Python dependencies).

Reads scripts/icons/icons.txt, fetches the pinned @phosphor-icons/core release (MIT) from the npm registry at
generation time (never at build time) and writes
core/designsystem/src/main/kotlin/dev/hfps/reveal/designsystem/icons/PhosphorRegular.kt and PhosphorFill.kt.

    python3 scripts/icons/generate_icons.py            # regenerate
    python3 scripts/icons/generate_icons.py --check    # fail if the committed files differ

Adding an icon: append its Phosphor name to icons.txt and run the script. Bumping Phosphor: change VERSION.
"""
import io
import re
import sys
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "2.1.1"
URL = f"https://registry.npmjs.org/@phosphor-icons/core/-/core-{VERSION}.tgz"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "core/designsystem/src/main/kotlin/dev/hfps/reveal/designsystem/icons"
NAMES = ROOT / "scripts/icons/icons.txt"
WEIGHTS = {"regular": "Regular", "fill": "Fill"}


def pascal(name):
    return "".join(p.capitalize() for p in name.split("-"))


def fetch():
    with urllib.request.urlopen(URL) as r:
        data = r.read()
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def path_data(svg_text, label):
    root = ET.fromstring(svg_text)
    paths = []
    for el in root:
        tag = el.tag.split("}")[1]
        if tag != "path":
            sys.exit(f"{label}: unsupported element <{tag}>; extend generate_icons.py")
        paths.append(el.attrib["d"])
    return paths


def render(weight, names, tar):
    obj = WEIGHTS[weight]
    lines = [
        "// GENERATED by scripts/icons/generate_icons.py from @phosphor-icons/core "
        f"{VERSION} (MIT). Do not edit.",
        "@file:Suppress(\"ktlint\", \"MaxLineLength\", \"LargeClass\")",
        "",
        "package dev.hfps.reveal.designsystem.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.PathParser",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** Phosphor " + weight + " weight. */",
        f"object Phosphor{obj} {{",
    ]
    for n in names:
        member = f"{n}.svg" if weight == "regular" else f"{n}-fill.svg"
        try:
            svg = tar.extractfile(f"package/assets/{weight}/{member}").read().decode()
        except KeyError:
            sys.exit(f"missing icon {weight}/{member}")
        ds = path_data(svg, member)
        p = pascal(n)
        lines.append(f"    val {p}: ImageVector by lazy {{")
        lines.append(f"        ImageVector.Builder(\"{obj}{p}\", 24.dp, 24.dp, 256f, 256f).apply {{")
        for d in ds:
            lines.append("            addPath(")
            lines.append(f"                PathParser().parsePathString(\"{d}\").toNodes(),")
            lines.append("                fill = SolidColor(Color.Black),")
            lines.append("            )")
        lines.append("        }.build()")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    names = [l.strip() for l in NAMES.read_text().splitlines() if l.strip() and not l.startswith("#")]
    tar = fetch()
    OUT.mkdir(parents=True, exist_ok=True)
    bad = 0
    for weight, obj in WEIGHTS.items():
        text = render(weight, names, tar)
        target = OUT / f"Phosphor{obj}.kt"
        if "--check" in sys.argv:
            if not target.exists() or target.read_text() != text:
                print(f"{target} is out of date")
                bad = 1
        else:
            target.write_text(text)
            print(f"wrote {target.relative_to(ROOT)} ({len(names)} icons)")
    sys.exit(bad)


if __name__ == "__main__":
    main()
